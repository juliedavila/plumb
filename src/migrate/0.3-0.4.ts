// Migration step 0.3 to 0.4. Idempotent: run twice, it changes nothing the second time.
//
// - engine.yaml: writes schema: "0.4" and a namespace (the instance's name as a namespace, unless one is written);
//   with --root, writes root: <path of the shared root, relative to the instance>. A generated engine.yaml is left to
//   its importer.
// - Renames the deprecated keys in the hand-written files (src/migrate/keys.ts).
// - With --root: a root folder with no engine.yaml gets one (kind: root), and the instance's teams move into the root's
//   org layer as one proposed org patch in <root>/patches/, so the move is a decision a person accepts. Until it is
//   accepted the design keeps its teams; once it is, core/one-home names the design's teams to remove.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { basename, join, relative, resolve, sep } from "node:path";
import { namespaceProblem } from "../core/namespace.ts";
import { natCompare } from "../core/util.ts";
import { DEPRECATED_KEYS, renameKey } from "./keys.ts";
import { generatedBy, setTop, topValue } from "./text.ts";
import type { MigrateStep, Workspace } from "./index.ts";

const unq = (v: string | undefined) => v?.replace(/^["']|["']$/g, "").trim();

/** The instance's name as a namespace: lower case, hyphens for anything else, at most 24 characters. */
export function namespaceFor(name: string): string {
  return name.toLowerCase().replace(/[^a-z0-9-]+/g, "-").replace(/^[^a-z]+/, "").replace(/-+$/, "").slice(0, 24).replace(/-+$/, "");
}

const q = (s: string) => JSON.stringify(s);

function teamsMovePatch(id: string, ns: string, title: string, teams: Record<string, unknown>[], today: string): string {
  const lines = [
    "# Written by bun plumb.ts migrate --root. A proposed org patch: accepting it is a decision, and nothing moves until then.",
    `id: ${id}`,
    `title: ${q(`Move the teams of ${title} into the org layer`)}`,
    "status: proposed",
    "provenance:",
    "  author: agent",
    "  agent: { name: plumb-migrate, tool: bun plumb.ts migrate }",
    `  created: ${q(today)}`,
    "why: >-",
    `  The design ${ns} now imports this root. Its ${teams.length === 1 ? "team moves" : `${teams.length} teams move`} into the org layer, so every design`,
    "  names one set of teams. Once this patch is accepted, remove the teams list from the design's model.yaml;",
    "  core/one-home names the design's teams until then.",
    "ops:",
  ];
  for (const t of teams) {
    const v = Object.entries(t).filter(([, x]) => x !== undefined && x !== null && (typeof x !== "object")).map(([k, x]) => `${k}: ${typeof x === "string" ? q(x) : String(x)}`).join(", ");
    lines.push("  - op: add", "    kind: team", `    value: { ${v} }`);
  }
  return lines.join("\n") + "\n";
}

export const step0304: MigrateStep = {
  from: "0.3", to: "0.4",
  run(ws: Workspace) {
    const dir = ws.dir, engine = join(dir, "engine.yaml");
    let text = ws.read(engine);
    if (text === undefined) { ws.note(`${engine} is not there, so this is not an instance folder`); return; }
    const gen = generatedBy(text);
    let ns = unq(topValue(text, "namespace"));
    if (gen) ws.note(`engine.yaml is generated by ${gen}; its importer writes schema, namespace and root, so re-run it`);
    else {
      text = setTop(text, "schema", `"0.4"`, ["name"]);
      if (!ns) {
        const name = unq(topValue(text, "name")) || basename(dir);
        const cand = namespaceFor(name);
        const bad = namespaceProblem(cand);
        if (bad) ws.note(`no namespace written: the name "${name}" gives "${cand}", which ${bad.replace(/^"[^"]*" /, "")}; write namespace: in engine.yaml and run migrate again`);
        else { text = setTop(text, "namespace", cand, ["schema", "name"]); ns = cand; }
      }
      if (ws.opts.root) {
        const rel = relative(dir, resolve(ws.opts.root)).split(sep).join("/") || ".";
        text = setTop(text, "root", rel, ["namespace", "schema", "name"]);
      }
      ws.write(engine, text);
    }
    for (const entry of DEPRECATED_KEYS) {
      const f = join(dir, entry.file), t = ws.read(f);
      if (t === undefined || generatedBy(t)) continue;
      const r = renameKey(t, entry);
      if (r.unsafe) ws.note(`${entry.file}: the key ${entry.old} is written where it cannot be told apart from ${entry.path}; rename it to ${entry.new} by hand`);
      else if (r.lines.length) ws.write(f, r.text);
    }
    if (ws.opts.root) moveTeams(ws, ns, unq(topValue(text, "title")) || ns || basename(dir));
  },
};

function moveTeams(ws: Workspace, ns: string | undefined, title: string): void {
  const root = resolve(ws.opts.root!), rootEngine = join(root, "engine.yaml");
  if (ws.read(rootEngine) === undefined) {
    ws.write(rootEngine, "# The shared root (Plumb 0.4): seams.yaml holds the shared layer, org.yaml the organization's records.\nkind: root\nschema: \"0.4\"\n");
    ws.note(`${relative(process.cwd(), root) || root} had no engine.yaml: it is now a shared root (kind: root)`);
  }
  const model = ws.read(join(ws.dir, "model.yaml"));
  let teams: Record<string, unknown>[] = [];
  try { const m = model ? Bun.YAML.parse(model) as Record<string, unknown> : undefined; teams = Array.isArray(m?.teams) ? (m!.teams as Record<string, unknown>[]).filter((t) => t && typeof t === "object") : []; } catch { /* the build reports a model that does not parse */ }
  if (!teams.length) return;
  if (!ns) { ws.note("the teams are not moved: the design has no namespace yet"); return; }
  const pdir = join(root, "patches");
  const existing = existsSync(pdir) ? readdirSync(pdir).filter((f) => /\.ya?ml$/.test(f)) : [];
  const pending = ws.pending(pdir);
  if ([...existing, ...pending].some((f) => f.endsWith(`-move-teams-from-${ns}.yaml`))) return; // proposed already
  const ids = existing.map((f) => { try { return String((Bun.YAML.parse(readFileSync(join(pdir, f), "utf8")) as Record<string, unknown>)?.id ?? ""); } catch { return ""; } });
  const n = Math.max(0, ...[...ids, ...pending].map((x) => Number(/^P-(\d+)/.exec(x)?.[1] ?? 0))) + 1;
  const id = `P-${String(n).padStart(3, "0")}`;
  ws.write(join(pdir, `${id}-move-teams-from-${ns}.yaml`), teamsMovePatch(id, ns, title, teams, ws.today));
  ws.note(`the ${teams.length === 1 ? "team" : `${teams.length} teams`} of ${ns} (${teams.map((t) => String(t.id)).sort(natCompare).join(", ")}) are proposed for the org layer in ${id}; accept it, then remove them from model.yaml`);
}
