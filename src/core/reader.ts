// Reader text: a finding's message with every record id it names replaced by the record's name.
//
// Rules write messages for the author and for agents ("unit U-01 has no owner team", "PM-1 is untested and
// records rest on it", "p07 writes evidence from check-runner"); those stay in `message`, where plumb check,
// the MCP server and the tests read them. A reader of the page sees `text`: the same sentence with names
// ("unit “Hook merge requests” has no owner team"). Ids stay on the record's hover card and full page.

import type { Bundle, Finding, Model, Plan, SharedCapability, Unit } from "../types.ts";
import { parseRef } from "./namespace.ts";

/** A claim is named by its statement, cut at a word near `max` characters. */
export function claimShort(statement: string, max = 80): string {
  const s = statement.trim().replace(/\s+/g, " ").replace(/[.\s]+$/, "");
  if (s.length <= max) return s;
  const cut = s.slice(0, max);
  const i = cut.lastIndexOf(" ");
  return `${(i > 40 ? cut.slice(0, i) : cut).replace(/[,;:\s]+$/, "")}…`;
}

const q = (s: string) => `“${s}”`;

/** id -> how a reader names it, by kind; `any` holds every id that is unambiguous across kinds. */
export interface Names { byKind: Map<string, Map<string, string>>; any: Map<string, string> }

/** Prefer the declared capability name. Older plans have only keys, which read as words. */
export function capabilityName(id: string, capabilities: SharedCapability[] = []): string {
  const bare = parseRef(id).id;
  return capabilities.find((c) => c.id === id || parseRef(c.id).id === bare)?.name
    ?? bare.replace(/^cap\./, "").replace(/[-_.]+/g, " ").trim();
}

/** Repair wording generated by older imports without rewriting published inputs or their hashes. */
export function readerUnitTitle(u: Unit, capabilities: SharedCapability[] = []): string {
  let title = u.title;
  for (const id of u.provides ?? []) {
    const prefix = title.match(/^[a-z][a-z0-9-]*:cap\./i)?.[0];
    if (!prefix) continue;
    const leaked = prefix + parseRef(id).id.replace(/^cap\./, "").replace(/-/g, " ");
    if (title.toLowerCase().startsWith(leaked.toLowerCase())) {
      const name = capabilityName(id, capabilities);
      title = name.charAt(0).toUpperCase() + name.slice(1) + title.slice(leaked.length);
    }
  }
  return title;
}

export function recordNames(model: Model, plan: Plan, extra: { patches?: { id: string; title: string }[]; capabilities?: SharedCapability[]; namespace?: string } = {}): Names {
  const byKind = new Map<string, Map<string, string>>();
  const put = (kind: string, id: string, name: string | undefined) => {
    if (!id || !name) return;
    let m = byKind.get(kind); if (!m) byKind.set(kind, (m = new Map()));
    if (!m.has(id)) m.set(id, name);
  };
  const el = new Map(model.elements.map((e) => [e.id, e.name]));
  for (const e of model.elements) put("element", e.id, e.name);
  for (const r of model.relationships) put("relationship", r.id, `${el.get(r.from) ?? r.from} → ${el.get(r.to) ?? r.to}`);
  for (const t of model.teams) put("team", t.id, t.name);
  for (const z of model.zones) put("zone", z.id, z.name);
  for (const s of model.systems) put("system", s.id, s.name);
  for (const v of model.views) put("view", v.id, q(v.title));
  for (const c of model.claims ?? []) put("claim", c.id, q(claimShort(c.statement)));
  const capabilities = [...(plan.capabilities ?? []), ...(extra.capabilities ?? [])];
  for (const u of plan.units) put("unit", u.id, q(readerUnitTitle(u, capabilities)));
  for (const p of plan.phases) put("phase", p.id, q(p.name));
  for (const p of extra.patches ?? []) put("patch", p.id, q(p.title));
  for (const c of model.contracts) put("contract", c.name, parseRef(c.name).id);
  for (const c of capabilities) {
    put("capability", c.id, capabilityName(c.id, capabilities));
    if (!parseRef(c.id).ns) put("capability", `shared:${c.id}`, capabilityName(c.id, capabilities));
  }
  for (const s of model.seams ?? []) put("seam", s.id, String(s.name ?? s.attrs?.name ?? parseRef(s.id).id));
  if (extra.namespace) for (const [kind, m] of byKind) for (const [id, name] of [...m]) {
    if (!parseRef(id).ns) put(kind, `${extra.namespace}:${id}`, name);
  }
  // A composed finding may still quote a bare id from its design's rule message. Resolve it only when unique.
  for (const [kind, m] of byKind) {
    const aliases = new Map<string, string[]>();
    for (const [id, name] of m) if (parseRef(id).ns) {
      const bare = parseRef(id).id;
      aliases.set(bare, [...(aliases.get(bare) ?? []), name]);
    }
    for (const [id, names] of aliases) if (names.length === 1) put(kind, id, names[0]);
  }
  const any = new Map<string, string>(), seen = new Map<string, number>();
  for (const m of byKind.values()) for (const id of m.keys()) seen.set(id, (seen.get(id) ?? 0) + 1);
  for (const m of byKind.values()) for (const [id, n] of m) if (seen.get(id) === 1) any.set(id, n);
  return { byKind, any };
}

const KIND_WORD: Record<string, string> = {
  unit: "unit", units: "unit", part: "element", parts: "element", element: "element", elements: "element", team: "team", teams: "team",
  claim: "claim", claims: "claim", premise: "claim", premises: "claim", assumption: "claim", milestone: "phase", phase: "phase",
  patch: "patch", change: "patch", path: "element", "→": "element", relationship: "relationship", relationships: "relationship", view: "view", zone: "zone", system: "system",
};

/**
 * Replace the record ids in a sentence with names. An id is replaced where it looks like an id (it holds a digit, a
 * dot or a hyphen) or where a kind word stands before it ("team product"); a finding key (pack/rule@at) is left alone.
 */
export function nameIds(text: string, names: Names): string {
  for (const [k, w] of CONFIG_WORDS) text = text.split(k).join(w);
  const parts = text.split(/(\s+)/);
  let prevWord = "";
  return parts.map((tok) => {
    if (/^\s+$/.test(tok) || !tok) return tok;
    const m = tok.match(/^([(“"'[]*)(.*?)((?:'s)?[)”"'\].,;:!?]*)$/);
    if (!m) { prevWord = tok.toLowerCase(); return tok; }
    const [, pre, core, post] = m;
    const kind = KIND_WORD[prevWord];
    prevWord = core.toLowerCase();
    if (!core || core.includes("@")) return tok; // a finding key stays as written
    const byKind = kind ? names.byKind.get(kind)?.get(core) : undefined;
    if (byKind) return pre + byKind + post;
    if (/[-.\d:]/.test(core)) { const n = names.any.get(core); if (n) return pre + n + post; }
    return tok;
  }).join("")
    // 'Unit “X” (“X”)': a quoted name followed by itself in brackets, said once
    .replace(/(“([^”]+)”) \(“\2”\)/g, "$1")
    // "element Code review (Code review)": the name once is enough
    .replace(/(“[^”]+”|[A-Z][^()]{2,80}?) \((?:“)?([^()”]+)(?:”)?\)/g, (all, a: string, b: string) => (a.replace(/[“”]/g, "") === b ? a : all));
}

/** Config and attribute keys a rule names, in words, for the reader (the key stays in the message and on Checks' "How this is checked"). */
const CONFIG_WORDS: [string, string][] = [
  ["numeric attrs.wip_limit", "numeric WIP limit"], ["attrs.wip_limit", "WIP limit"], ["attrs.wait_days", "wait in days"],
  [" (engine.yaml flow.max_age_days)", ""], ["wip_limit", "WIP limit"], ["wait_days", "wait in days"], ["work_days", "work in days"],
  ["flow_source (measured, estimated or declared)", "source (measured, estimated or declared)"], ["flow_source", "source"], ["flow_as_of", "as-of"],
  ["partitioned_by", "partition key"], ["owner_team.match", "the tracker mapping's team values"],
];

/** Every finding the page shows gets its reader text: the bundle's own, and those in each patch's impact. */
export function addReaderText(b: Bundle, capabilities: SharedCapability[] = []): void {
  for (const u of b.plan.units) u.title = readerUnitTitle(u, capabilities);
  const names = recordNames(b.model, b.plan, { patches: b.patches, capabilities, namespace: b.instance.namespace });
  for (const link of b.premiseLinks?.links ?? []) for (const side of ["from", "to"] as const) {
    if (!names.byKind.has("claim")) names.byKind.set("claim", new Map());
    const shown = q(claimShort(link.statements[side]));
    names.byKind.get("claim")!.set(link[side], shown);
    names.any.set(link[side], shown);
  }
  const one = (nm: Names) => (f: Finding) => {
    const t = f.pack === "premises" && f.rule === "links-valid" && f.message.includes("absent from scope")
      ? "This link names a premise in a design outside this workspace and is skipped." : nameIds(f.message, nm);
    if (t !== f.message) f.text = t;
  };
  b.findings.forEach(one(names));
  for (const p of b.patches) {
    // a record the patch adds or removes is named from the patch's own snapshot
    const nm: Names = { byKind: new Map([...names.byKind].map(([k, m]) => [k, new Map(m)])), any: new Map(names.any) };
    for (const [key, snap] of Object.entries(p.impact.records ?? {})) {
      const i = key.indexOf(":"), kind = key.slice(0, i), id = key.slice(i + 1);
      const n = (snap as { name?: string }).name;
      if (!n || nm.byKind.get(kind)?.has(id)) continue;
      const shown = kind === "element" || kind === "team" || kind === "zone" || kind === "system" ? n : q(n);
      if (!nm.byKind.has(kind)) nm.byKind.set(kind, new Map());
      nm.byKind.get(kind)!.set(id, shown);
      if (!nm.any.has(id)) nm.any.set(id, shown);
    }
    const im = p.impact as unknown as Record<string, unknown>;
    for (const k of Object.keys(im)) {
      const v = im[k];
      if (Array.isArray(v) && v.length && typeof v[0] === "object" && v[0] && "rule" in v[0] && "message" in v[0]) (v as Finding[]).forEach(one(nm));
    }
  }
}
